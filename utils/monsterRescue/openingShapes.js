/**
 * @param {number} levelId 1–60
 * @returns {string} A–Z
 */
export function shapeLetterForLevel(levelId) {
  const idx = Math.max(1, Math.floor(levelId || 1)) - 1;
  return OPENING_SHAPE_LETTERS[idx % 26];
}

/**
 * @param {string} letter A–Z
 * @returns {string[]}
 */
export function getShapeMask(letter) {
  const key = String(letter || 'A')
    .toUpperCase()
    .slice(0, 1);
  return SHAPE_MASKS[key] ?? SHAPE_MASKS.A;
}

/**
 * Whether a bubble exists at (row, col) for this opening shape.
 * @param {string} letter
 * @param {number} row
 * @param {number} col
 * @param {number} maxCol exclusive upper bound for staggered row width
 */
export function shapeHasBubble(letter, row, col, maxCol) {
  const mask = getShapeMask(letter);
  if (row < 0 || row >= mask.length || col < 0 || col >= maxCol) return false;
  const line = mask[row];
  if (!line || col >= line.length) return false;
  return line[col] === '#';
}
